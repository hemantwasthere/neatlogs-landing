export type WordmarkCell = { x: number; y: number };

export const wordmarkColumns = rows[0].length;
export const wordmarkLines = rows.length;

const cells: WordmarkCell[] = rows.flatMap((row, y) =>
  [...row].flatMap((cell, x) => (cell === "#" ? [{ x, y }] : [])),
);

const filledColumns = new Set(cells.map((cell) => cell.x));

const columnRuns = Array.from({ length: wordmarkColumns }, (_, x) => x).reduce<
  number[][]
>((runs, x) => {
  if (!filledColumns.has(x)) return runs;

  const last = runs.at(-1);

  if (last && last.at(-1) === x - 1) last.push(x);
  else runs.push([x]);

  return runs;
}, []);

export const wordmarkGlyphs = columnRuns.map((run) => {
  const from = run[0];
  const to = run.at(-1) as number;

  return cells.filter((cell) => cell.x >= from && cell.x <= to);
});

export function wordmarkViewBox(radius: number) {
  const bleed = Math.max(radius - 0.5, 0) + 0.08;

  return `${-bleed} ${-bleed} ${wordmarkColumns + bleed * 2} ${wordmarkLines + bleed * 2}`;
}

export function wordmarkPath(radius: number, group: WordmarkCell[] = cells) {
  const span = radius * 2;

  return group
    .map(({ x, y }) => {
      const cx = (x + 0.5 - radius).toFixed(3);
      const cy = (y + 0.5).toFixed(3);

      return `M${cx} ${cy}a${radius} ${radius} 0 1 0 ${span} 0a${radius} ${radius} 0 1 0 ${-span} 0`;
    })
    .join("");
}
